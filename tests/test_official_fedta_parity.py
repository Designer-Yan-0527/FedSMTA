def run_main(extra):
    cmd = [sys.executable, "main.py", "datasets_delay"] + extra
    print("+", " ".join(cmd), flush=True)
    proc = subprocess.run(cmd, cwd=str(REPO_ROOT))
    if proc.returncode != 0:
        raise RuntimeError(f"command failed: {' '.join(cmd)}")


def main():
    args = parse_args()
    total = args.task_num * args.global_epoch
    if args.rounds != total:
        raise SystemExit(
            f"--rounds must equal task_num*global_epoch ({total}): the "
            "official repo always runs its full task loop, so the fork "
            "side must run the same number of rounds")

    official_repo = Path(args.official_repo).expanduser().resolve()
    for rel in ("main.py", "Models", "config"):
        if not (official_repo / rel).exists():
            raise SystemExit(
                f"--official_repo does not look like the official FedTA "
                f"repo: missing {rel!r} under {official_repo}")
    official_python = args.official_python or sys.executable

    tag = f"{os.getpid()}_{int(time.time())}"
    driver_path = official_repo / f"_parity_driver_{tag}.py"
    payload_path = official_repo / f"_parity_payload_{tag}.json"
    dump_path = official_repo / f"_parity_dump_{tag}.pth"

    strict_overrides = {
        "client_num": args.client_num,
        "task_num": args.task_num,
        "private_class_num": args.private_class_num,
        "global_epoch": args.global_epoch,
        "local_epoch": args.local_epoch,
        "batch_size": args.batch_size,
        "seed": args.seed,
        "lr": args.lr,
        "method": args.method,
        "device": args.device,
        "model": "vit_base_patch16_224",
        "model_name": "Tail_Anchor",
        "input_size": 224,
    }
    lenient_overrides = {
        "data_path": args.data_path,
        "surrogate_num": args.surrogate_num,
        "threshold": args.threshold,
    }
    assert sorted(strict_overrides) == sorted(STRICT_OVERRIDE_KEYS)
    assert sorted(lenient_overrides) == sorted(LENIENT_OVERRIDE_KEYS)

    payload = {
        "config_module_candidates": (
            [args.config_module] if args.config_module
            else CONFIG_MODULE_CANDIDATES),
        "vit_module_candidates": VIT_MODULE_CANDIDATES,
        "strict_overrides": strict_overrides,
        "lenient_overrides": lenient_overrides,
        "dump_path": str(dump_path),
    }
    driver_path.write_text(DRIVER_SOURCE, encoding="utf-8")
    payload_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")

    run_dir = (args.work_dir / args.data_name / args.method
               / "parity_fedta" / f"seed_{args.seed}")
    if run_dir.exists():
        print(f"[cleanup] removing previous test run dir {run_dir}")
        shutil.rmtree(run_dir)

    passed = False
    try:
        # ---------- side 1: the OFFICIAL repo (in-process driver) ----------
        cmd = [official_python, driver_path.name,
               "--payload", payload_path.name]
        print(f"[official] cwd={official_repo}")
        print("+", " ".join(cmd), flush=True)
        proc = subprocess.run(cmd, cwd=str(official_repo))
        if proc.returncode != 0:
            raise RuntimeError("official-repo parity driver failed")

        # ---------- side 2: the fork (fedta, observers off) ----------
        base = ["--data_name", args.data_name,
                "--data-path", args.data_path,
                "--seed", str(args.seed), "--device", args.device,
                "--client_num", str(args.client_num),
                "--task_num", str(args.task_num),
                "--private_class_num", str(args.private_class_num),
                "--global_epoch", str(args.global_epoch),
                "--local_epoch", str(args.local_epoch),
                "--batch-size", str(args.batch_size),
                "--surrogate_num", str(args.surrogate_num),
                "--threshold", str(args.threshold),
                "--lr", str(args.lr),
                "--method", args.method,
                "--deterministic", "--no_instrumentation",
                "--save_every", "1",
                "--output_dir", str(args.work_dir),
                "--max_rounds", str(args.rounds)]
        run_main(base + ["--run_name", "parity_fedta"])

        dump = torch.load(dump_path, map_location="cpu", weights_only=False)
        ckpt = torch.load(run_dir / "checkpoints" / "latest.pth",
                          map_location="cpu", weights_only=False)

        # ---------- Gate 0A seals (hard asserts, no vacuous pass) ----------
        assert ckpt["args"].get("no_instrumentation") is True, (
            "fork checkpoint must record no_instrumentation=True: the "
            "parity baseline is FedTA + checkpoint only")
        assert ckpt["args"].get("deterministic") is True, (
            "fork checkpoint must record deterministic=True (the official "
            "driver runs cudnn.deterministic=True as well)")
        assert int(ckpt["completed_round"]) == args.rounds - 1, (
            f"fork run must complete all {args.rounds} rounds "
            f"(completed_round={ckpt['completed_round']})")
        ids_fork = [c["id"] for c in ckpt["clients"]]
        ids_official = [c["id"] for c in dump["clients"]]
        assert ids_fork == ids_official, (
            f"client id order differs: fork={ids_fork}, "
            f"official={ids_official}")
        # both manifests must exist and be non-empty (no {} == {} pass)
        outer_fork = require_outer_manifest(ckpt, str(run_dir))
        outer_official = dump["outer_split_manifest"]
        assert isinstance(outer_official, dict) and outer_official, (
            "official dump missing outer_split_manifest (driver bug)")

        # ---------- state comparison (goal: D = 0 everywhere) ----------
        head_diffs = [state_dict_diff(ckpt["global_head"],
                                      dump["global_head"])]
        key_diffs, anchor_diffs, ta_diffs, cprompt_diffs = [], [], [], []
        for cf, co in zip(ckpt["clients"], dump["clients"]):
            assert len(cf["heads"]) == len(co["heads"]), (
                f"client {cf['id']}: head count differs "
                f"(fork={len(cf['heads'])}, official={len(co['heads'])})")
            for hf, ho in zip(cf["heads"], co["heads"]):
                head_diffs.append(state_dict_diff(hf, ho))
            ta_f, ta_o = cf["tail_anchor_model"], co["tail_anchor_model"]
            ta_diffs.append(state_dict_diff(ta_f, ta_o))
            key_diffs.append(max_diff(ta_f.get("key"), ta_o.get("key")))
            anchor_diffs.append(max_diff(ta_f.get("anchor_pool"),
                                         ta_o.get("anchor_pool")))
            cprompt_diffs.append(state_dict_diff(cf.get("prompts"),
                                                 co.get("prompts")))

        # inner 70/30 splits (fork uses int client/task keys -> normalize)
        inner_fork = {str(cid): {str(t): s for t, s in tasks.items()}
                      for cid, tasks in
                      (ckpt.get("data_split_state") or {}).items()}
        inner_official = dump["inner_splits"]
        split_equal = bool(deep_equal(inner_fork, inner_official))
        outer_equal = bool(deep_equal(outer_fork, outer_official))

        comparison = {
            "completed_round_diff": abs(int(ckpt["completed_round"])
                                        - int(dump["completed_round"])),
            "server_model_max_diff": state_dict_diff(ckpt["server_model"],
                                                     dump["server_model"]),
            "global_proto_max_diff": protos_diff(ckpt["global_protos"],
                                                 dump["global_protos"]),
            "temp_proto_max_diff": protos_diff(ckpt.get("temp_protos"),
                                               dump.get("temp_protos")),
            "prompt_max_diff": state_dict_diff(ckpt["server_prompt"],
                                               dump["server_prompt"]),
            "client_prompt_max_diff": (max(cprompt_diffs)
                                       if cprompt_diffs else 0.0),
            "head_max_diff": max(head_diffs),
            "key_max_diff": max(key_diffs),
            "anchor_max_diff": max(anchor_diffs),
            "tail_anchor_state_max_diff": max(ta_diffs) if ta_diffs else 0.0,
            "split_equal": split_equal,
            "outer_split_equal": outer_equal,
            "fix_keys_equal": sorted(map(str, ckpt["fix_keys"]))
                              == sorted(map(str, dump["fix_keys"])),
        }

        # ---------- pass/fail report ----------
        report = []
        for name, diff in comparison.items():
            if name in ("split_equal", "outer_split_equal",
                        "fix_keys_equal"):
                report.append((name, diff is True,
                               0.0 if diff else float("inf"), ""))
            else:
                report.append((name, diff == 0.0, diff, ""))

        print("\n===== official FedTA parity report =====")
        all_ok = True
        for name, ok, diff, note in report:
            status = "PASS" if ok else "FAIL"
            all_ok &= ok
            print(f"[{status}] {name:26s} max_diff={diff}"
                  f"{('  (' + note + ')') if note else ''}")

        result = "PASS" if all_ok else "FAIL"
        passed = all_ok

        fork_record = {
            "run_dir": str(run_dir),
            "completed_round": int(ckpt["completed_round"]),
            "outer_split_hash": hash_obj(outer_fork),
            "inner_split_hash": hash_obj(inner_fork),
            "global_protos_checksum": hash_obj(ckpt.get("global_protos")),
            "global_head_checksum": hash_obj(ckpt.get("global_head")),
            "server_prompt_checksum": hash_obj(ckpt.get("server_prompt")),
            "server_model_checksum": hash_obj(ckpt.get("server_model")),
            "key_checksums": {str(c["id"]): hash_obj(
                c["tail_anchor_model"].get("key"))
                for c in ckpt["clients"]},
            "anchor_pool_checksums": {str(c["id"]): hash_obj(
                c["tail_anchor_model"].get("anchor_pool"))
                for c in ckpt["clients"]},
            "args": ckpt.get("args"),
        }
        official_record = {
            "official_repo": str(official_repo),
            "dump_path": str(dump_path),
            "config_module": dump.get("config_module"),
            "dropped_spliter_kwargs": dump.get("dropped_spliter_kwargs"),
            "dropped_server_kwargs": dump.get("dropped_server_kwargs"),
            "lenient_overrides_absent_from_config":
                dump.get("lenient_overrides_absent_from_config"),
            "completed_round": int(dump["completed_round"]),
            "outer_split_hash": hash_obj(outer_official),
            "inner_split_hash": hash_obj(inner_official),
            "global_protos_checksum": hash_obj(dump.get("global_protos")),
            "global_head_checksum": hash_obj(dump.get("global_head")),
            "server_prompt_checksum": hash_obj(dump.get("server_prompt")),
            "server_model_checksum": hash_obj(dump.get("server_model")),
            "key_checksums": {str(c["id"]): hash_obj(
                c["tail_anchor_model"].get("key"))
                for c in dump["clients"]},
            "anchor_pool_checksums": {str(c["id"]): hash_obj(
                c["tail_anchor_model"].get("anchor_pool"))
                for c in dump["clients"]},
            "official_args": dump.get("official_args"),
        }

        verification = {
            "test": "official_fedta_parity",
            "gate": "Gate 0A: FedSMTA --method fedta must be bit-identical "
                    "to the official FedTA (D=0)",
            "generated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
            "result": result,
            "config": {
                "data_name": args.data_name, "method": args.method,
                "seed": args.seed, "rounds": args.rounds,
                "global_epoch": args.global_epoch, "task_num": args.task_num,
                "local_epoch": args.local_epoch,
                "client_num": args.client_num,
                "private_class_num": args.private_class_num,
                "batch_size": args.batch_size,
                "surrogate_num": args.surrogate_num,
                "threshold": args.threshold, "lr": args.lr,
                "deterministic": True, "no_instrumentation": True,
            },
            "fork_run": fork_record,
            "official_run": official_record,
            "comparison": {k: (None if v == float("inf") else v)
                           for k, v in comparison.items()},
            "notes": [
                "accuracy is NOT gating in v1: D=0 over all model states "
                "and both splits implies identical evaluation outputs",
                "RNG states cannot be compared: the official repo has no "
                "checkpoint mechanism",
                "both sides run with cudnn.deterministic=True (fork "
                "--deterministic mirrors the driver)",
                "if tiny nonzero diffs appear, first suspect GPU/operator "
                "nondeterminism and rerun; do NOT loosen the tolerance",
            ],
        }
        out_path = (Path(args.work_dir) / "metrics"
                    / "official_fedta_parity.json")
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(verification, f, indent=2, default=str)

        print(f"\nsaved {out_path}")
        print("\nRESULT:", result if all_ok else
              "FAIL (the fedta path diverges from the official FedTA; "
              "compare the checksums in the JSON to locate the first "
              "diverging component)")
    finally:
        if args.keep_driver or not passed:
            print(f"[debug] keeping parity driver artifacts in "
                  f"{official_repo}: {driver_path.name}, "
                  f"{payload_path.name}, {dump_path.name}")
        else:
            for p in (driver_path, payload_path, dump_path):
                try:
                    p.unlink()
                except OSError:
                    pass

    sys.exit(0 if passed else 1)


