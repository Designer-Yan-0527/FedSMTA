"""Gate 0A: official FedTA <-> FedSMTA baseline parity test.

Gate 0B (resume regression) only proves "our code continuous == our code
resumed". This test proves the stronger statement:

    FedSMTA --method fedta --no_instrumentation  ==  Official FedTA

It runs the OFFICIAL FedTA repo in-process through a generated driver
script (the official repo has no checkpoint mechanism, so the driver
exports the final state right after myServer.start()), runs the fork with
the frozen short-parity configuration, and compares:

  server model / global head / global protos / temp protos / server prompt,
  per-client heads / tail-anchor key / anchor_pool / full tail-anchor state
  / prompts, fix_keys, the federated outer split manifest (raw indices +
  class masks) and the inner 70/30 split indices per (client, task).

PASS requires D = 0 EXACTLY (no floating-point tolerance): if tiny nonzero
diffs appear, first suspect GPU/operator nondeterminism and rerun — do NOT
loosen the tolerance to make it pass.

v1 limitations (documented, not gating):
  - accuracy is not compared directly: D = 0 over all model states and both
    splits implies identical evaluation outputs;
  - RNG states cannot be compared (the official repo saves nothing).

Writes metrics/official_fedta_parity.json under --work_dir.

Prerequisites:
  - --official_repo: a local clone of the official FedTA repo, with its
    dataset reachable (if the official spliter hardcodes the dataset path,
    prepare that path; any dropped kwarg is reported in the JSON);
  - pretrain_model/ViT-B_16.npz under the official repo;
  - same GPU for both sides; --official_python if the official repo needs
    a different environment.

Usage (ON THE SERVER, from the repo root):

  python tests/test_official_fedta_parity.py \
      --official_repo /path/to/official_FedTA \
      --data_path ./local_datasets
"""

