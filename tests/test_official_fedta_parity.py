def _import_first(candidates, what):
    errors = []
    for name in candidates:
        try:
            return __import__(name, fromlist=["*"]), name
        except Exception as exc:
            errors.append("  %s: %r" % (name, exc))
    raise SystemExit("[parity-driver] cannot import %s; tried:\n%s"
                     % (what, "\n".join(errors)))


def _module_state(module):
    if module is None:
        return None
    return {k: v.detach().cpu() for k, v in module.state_dict().items()}


# ---------------------------------------------------------------------------
# Patch random_split BEFORE Models.Client_DF is imported (it binds
# random_split at module import time). The official repo does not record
# the inner 70/30 split indices; the fork stores them as
# data_split_indices, so we capture the same content here: per (client,
# task) the train/test Subset.indices.
# ---------------------------------------------------------------------------
_inner_splits = {}
_split_ctx = {"ctx": None}
_orig_random_split = torch.utils.data.random_split


def _recording_random_split(dataset, *split_args, **split_kwargs):
    subsets = _orig_random_split(dataset, *split_args, **split_kwargs)
    ctx = _split_ctx["ctx"]
    if ctx is not None and len(subsets) == 2:
        cid, tid = ctx
        _inner_splits.setdefault(str(cid), {})[str(tid)] = {
            "train": [int(x) for x in subsets[0].indices],
            "test": [int(x) for x in subsets[1].indices],
        }
    return subsets


torch.utils.data.random_split = _recording_random_split


